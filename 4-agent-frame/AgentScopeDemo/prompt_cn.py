# -*- coding: utf-8 -*-
"""三国狼人杀中文提示词

提示词设计思路：
    1. 基础提示词 (base_prompt) 包含两层信息：
       - 角色身份（三国角色 + 游戏身份）
       - JSON 输出格式约束（让智能体返回可解析的结构化数据）
    2. 角色特定提示词 在基础提示词后追加阵营策略和性格特点
    3. 三国性格 通过 {character} 变量动态插入，让智能体以特定历史人物的口吻说话

提示词会被传入 ReActAgent 的 sys_prompt 参数，作为系统消息发送给 LLM。
"""


class ChinesePrompts:
    """中文提示词管理类

    职责：根据角色身份和游戏阵营，生成对应的系统提示词。
    提示词由「基础模板 + 角色特定规则」两部分拼接而成。
    """

    @staticmethod
    def get_role_prompt(role: str, character: str) -> str:
        """根据角色身份和游戏阵营生成系统提示词

        提示词结构：
        - 身份声明：告诉 LLM 它扮演谁、是什么身份
        - JSON 格式约束：要求智能体以固定格式返回，便于程序解析
        - 角色特定规则：根据阵营（狼人/预言家/女巫/猎人/村民）定义行为策略
        - 三国性格：让智能体以特定历史人物的口吻说话

        Args:
            role: 游戏身份，如 "狼人"、"预言家"、"女巫"、"猎人"、"村民"
            character: 三国角色名，如 "刘备"、"曹操" 等

        Returns:
            完整的系统提示词字符串
        """
        # 基础提示词：所有角色共享
        # - {{ }} 双花括号是因为在 f-string 中表示字面量花括号（输出 JSON 示例）
        # - 注意：这里的 JSON 示例只是引导格式，实际结构化输出由 structured_output_cn.py 中的 Pydantic 模型控制
        base_prompt = f"""你是{character}，在这场三国狼人杀游戏中扮演{role}。

请严格按照以下JSON格式回复，不要添加任何其他文字：
{{
    "reach_agreement": true/false,
    "confidence_level": 1-10的数字,
    "key_evidence": "你的证据或观点"
}}

角色特点：
"""

        # ---- 根据阵营生成角色特定提示词 ----
        # 每个阵营的提示词包含：阵营目标 + 技能说明 + 策略指导 + 性格融入
        if role == "狼人":
            return base_prompt + f"""
- 你是狼人阵营，目标是消灭所有好人
- 夜晚可以与其他狼人协商击杀目标
- 白天要隐藏身份，误导好人
- 以{character}的性格说话和行动
"""
        elif role == "预言家":
            return base_prompt + f"""
- 你是好人阵营的预言家，目标是找出所有狼人
- 每晚可以查验一名玩家的真实身份
- 要合理公布查验结果，引导好人投票
- 以{character}的智慧和洞察力分析局势
"""
        elif role == "女巫":
            return base_prompt + f"""
- 你是好人阵营的女巫，拥有解药和毒药各一瓶
- 解药可以救活被狼人击杀的玩家
- 毒药可以毒杀一名玩家
- 要谨慎使用道具，在关键时刻发挥作用
"""
        elif role == "猎人":
            return base_prompt + f"""
- 你是好人阵营的猎人
- 被投票出局时可以开枪带走一名玩家
- 要在关键时刻使用技能，带走狼人
- 以{character}的勇猛和决断力行动
"""
        else:  # 村民
            return base_prompt + f"""
- 你是好人阵营的村民
- 没有特殊技能，只能通过推理和投票
- 要仔细观察，找出狼人的破绽
- 以{character}的性格参与讨论
"""